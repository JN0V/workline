







































































































































































































































































































































































































































    static bool pruneMap(Map& m, Pred pred) {
        bool found = false;
        for (auto it = m.begin(); it != m.end(); ) {
            auto& vec = it->second;
            size_t oldSize = vec.size();
            vec.erase(std::remove_if(vec.begin(), vec.end(), pred), vec.end());
            if (vec.size() != oldSize) {
                vec.shrink_to_fit();
                found = true;
            }
            if (vec.empty()) it = m.erase(it);
            else ++it;
        }
        return found;
    }










































